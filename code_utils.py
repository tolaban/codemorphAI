from schemas import FullResponse, RecommendationResult
import os
import io
import altair as alt
import pandas as pd
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
import vl_convert as vlc
from datetime import datetime

def generate_word_docs(response: FullResponse, recommendation: RecommendationResult = None, metadata: dict = None, source_lang: str = "Unknown") -> io.BytesIO:
    analysis = response.analysis
    mod = response.modernization
    target_lang = mod.target_language if mod else "N/A"

    doc = Document()

    # Apply some basic styles (if header/footer manipulation is needed, doc.sections[0].header)
    section = doc.sections[0]
    header = section.header
    header_para = header.paragraphs[0]
    if metadata:
        header_para.text = f"CodeMorph AI Assessment | {metadata.get('doc_id')} | v{metadata.get('current_version')} | {metadata.get('status')}"
        header_para.alignment = WD_ALIGN_PARAGRAPH.RIGHT

    # Professional Title Page
    title = doc.add_heading('CodeMorph AI', 0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    subtitle = doc.add_paragraph('Modernization & Analysis Report')
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_page_break()

    # 0. Document Control
    doc.add_heading('Document Control', level=1)
    if metadata:
        current_rev = metadata.get("revisions", [{}])[-1] if metadata.get("revisions") else {}

        table = doc.add_table(rows=6, cols=2)
        table.style = 'Table Grid'

        records = [
            ("Document ID", metadata.get("doc_id", "")),
            ("Version", metadata.get("current_version", "")),
            ("Generated Date", current_rev.get("timestamp", "").split("T")[0]),
            ("Languages", f"Source: {source_lang} -> Target: {target_lang}"),
            ("Generated By", current_rev.get("generated_by", "")),
            ("Document Status", f"{metadata.get('status', '')}")
        ]

        for i, (key, value) in enumerate(records):
            table.rows[i].cells[0].text = str(key)
            table.rows[i].cells[0].paragraphs[0].runs[0].bold = True
            table.rows[i].cells[1].text = str(value)

        doc.add_heading('Revision History', level=2)
        rev_table = doc.add_table(rows=1, cols=4)
        rev_table.style = 'Table Grid'
        hdr_cells = rev_table.rows[0].cells
        hdr_cells[0].text = 'Version'
        hdr_cells[1].text = 'Date'
        hdr_cells[2].text = 'Summary'
        hdr_cells[3].text = 'Status'
        for cell in hdr_cells:
            cell.paragraphs[0].runs[0].bold = True

        for rev in reversed(metadata.get("revisions", [])):
            row_cells = rev_table.add_row().cells
            row_cells[0].text = str(rev.get("version", ""))
            row_cells[1].text = str(rev.get("timestamp", "")).split("T")[0]
            row_cells[2].text = str(rev.get("change_summary", ""))
            row_cells[3].text = str(rev.get("review_status", ""))

        doc.add_page_break()


    # 1. Executive Summary
    doc.add_heading('1. Executive Summary', level=1)
    doc.add_paragraph(analysis.summary)

    # 2. Existing Application Overview & Inputs/Outputs/Dependencies
    doc.add_heading('2. Existing Application Overview', level=1)
    if mod:
        doc.add_paragraph(f"Source Language: {mod.original_language}")
    doc.add_heading('Inputs, Outputs and Dependencies', level=2)
    if not analysis.dependencies:
        doc.add_paragraph("No specific external dependencies identified.")
    else:
        for dep in analysis.dependencies:
            doc.add_paragraph(dep, style='List Bullet')

    # 3. Extracted Business Rules
    doc.add_heading('3. Extracted Business Rules', level=1)
    if not analysis.business_rules:
        doc.add_paragraph("No specific business rules identified.")
    else:
        for idx, rule in enumerate(analysis.business_rules, 1):
            p = doc.add_paragraph()
            p.add_run(f"Rule {idx}: {rule.rule}").bold = True
            doc.add_paragraph(f"Context/Trigger: {rule.context}")

    # 4. Identified Defects and Technical Debt
    doc.add_heading('4. Identified Defects and Refactoring Opportunities', level=1)
    if not analysis.defects:
        doc.add_paragraph("No specific defects or technical debt identified.")
    else:
        for d in analysis.defects:
            p = doc.add_paragraph()
            p.add_run(f"[{d.severity}] {d.issue}").bold = True
            doc.add_paragraph(f"Location: {d.line_number}")
            doc.add_paragraph(f"Recommendation: {d.recommendation}")

    # 5. Modernization Target Recommendation
    if recommendation and recommendation.status == "Success":
        doc.add_heading('5. Modernization Target Recommendation', level=1)
        doc.add_paragraph(f"Recommended Target: {recommendation.recommended_language}", style='Heading 2')
        doc.add_paragraph(recommendation.business_justification)

        # Insert Chart
        chart_data = [{"Language": c.language, "Score": c.total_score} for c in recommendation.candidates]
        df_chart = pd.DataFrame(chart_data)

        bars = alt.Chart(df_chart).mark_bar().encode(
            x=alt.X('Score:Q', scale=alt.Scale(domain=[0, 100]), title='Suitability Score (0-100)'),
            y=alt.Y('Language:N', sort='-x', title=''),
            color=alt.condition(
                alt.datum.Language == recommendation.recommended_language,
                alt.value('#1f77b4'),
                alt.value('lightgray')
            )
        )
        text = bars.mark_text(align='left', baseline='middle', dx=3).encode(text='Score:Q')
        chart = (bars + text).properties(height=250, width=500)

        # Convert chart to PNG using vl_convert
        png_data = vlc.vegalite_to_png(chart.to_dict())
        image_stream = io.BytesIO(png_data)

        doc.add_picture(image_stream, width=Inches(5.5))
        doc.add_paragraph("Scores represent multi-dimensional heuristic decision support, not probabilities of migration success.", style='Intense Quote')

        doc.add_heading('Migration Risks & Assumptions', level=2)
        doc.add_paragraph().add_run("Challenges:").bold = True
        for chal in recommendation.migration_challenges:
             doc.add_paragraph(chal, style='List Bullet')

        doc.add_paragraph().add_run("Assumptions / Missing Info:").bold = True
        for asm in recommendation.assumptions_missing_info:
             doc.add_paragraph(asm, style='List Bullet')

        doc.add_heading('Recommended Next Steps', level=2)
        doc.add_paragraph(recommendation.migration_strategy)

    # 6. Proposed Improvements (Modernization output)
    if mod:
        doc.add_heading('6. Proposed Conversion / Improvements', level=1)
        doc.add_paragraph(f"Target Language: {mod.target_language}")
        doc.add_paragraph(mod.explanation)
        if mod.warnings:
            doc.add_heading('Validation Warnings', level=2)
            for w in mod.warnings:
                doc.add_paragraph(w, style='List Bullet')

    # Save to BytesIO
    docx_stream = io.BytesIO()
    doc.save(docx_stream)
    docx_stream.seek(0)
    return docx_stream

def get_sample_cobol() -> str:
    base_path = "sample_projects/NightmareBank_COBOL"
    files = ["ACCT-REC.cpy", "OVD-DRIVER.cbl", "FEE-CALC.cbl"]
    content = ""
    for file in files:
        file_path = os.path.join(base_path, file)
        if os.path.exists(file_path):
            with open(file_path, "r") as f:
                content += f"--- {file} ---\n{f.read()}\n\n"
    return content

